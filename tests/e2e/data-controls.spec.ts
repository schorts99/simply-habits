import { expect, test } from "@playwright/test";

test("backup preview, merge, permanent deletion and local clear work offline", async ({ page, context }) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/");
  await page.getByRole("button", { name: "New habit", exact: true }).click();
  await page.getByRole("textbox", { name: "Habit name", exact: true }).fill("Backup habit");
  await page.getByRole("spinbutton", { name: "Daily target" }).fill("2");
  await page.getByRole("button", { name: "Create habit", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Backup habit", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "Export my habits", exact: true }).click();
  const stream = await (await downloadPromise).createReadStream();
  const chunks: Buffer[] = [];
  for await (const chunk of stream!) chunks.push(Buffer.from(chunk));
  const backup = Buffer.concat(chunks);
  await expect(page.getByText("Ready for offline use", { exact: true })).toBeVisible();
  await page.waitForFunction(() => !!navigator.serviceWorker.controller);
  await context.setOffline(true);
  await page.getByRole("button", { name: "My habits", exact: true }).click();
  await page.getByRole("button", { name: "Edit Backup habit", exact: true }).click();
  await page.getByRole("textbox", { name: "Habit name", exact: true }).fill("Newer habit");
  await page.getByRole("button", { name: "Save changes", exact: true }).click();
  await page.getByRole("button", { name: "Check in Newer habit", exact: true }).click();
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  const input = page.getByLabel("Choose JSON backup");
  await input.setInputFiles({ name: "invalid.json", mimeType: "application/json", buffer: Buffer.from("{") });
  await expect(page.getByRole("alert").filter({ hasText: "Choose a valid Simply Habits JSON backup." })).toBeVisible();
  await expect(page.getByRole("button", { name: "Restore backup", exact: true })).toHaveCount(0);
  await input.setInputFiles({ name: "backup.json", mimeType: "application/json", buffer: backup });
  await expect(page.getByText("Ready to merge 1 habits into the current vault.", { exact: true })).toBeVisible();
  await expect(page.getByText("0 new · 0 merged · 1 unchanged · 0 deletion-blocked", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Restore backup", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "Backup merged." })).toBeVisible();
  await page.getByRole("button", { name: "My habits", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Newer habit", exact: true })).toBeVisible();
  await expect(page.locator(".habit-progress")).toContainText("1 / 2");
  await page.getByRole("button", { name: "Edit Newer habit", exact: true }).click();
  await page.getByRole("button", { name: "Delete habit permanently", exact: true }).click();
  await page.getByRole("button", { name: "Yes, permanently delete", exact: true }).click();
  await expect(page.locator(".habit-card")).toHaveCount(0);
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await input.setInputFiles({ name: "backup.json", mimeType: "application/json", buffer: backup });
  await expect(page.getByText("0 new · 0 merged · 0 unchanged · 1 deletion-blocked", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Restore backup", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "Backup merged." })).toBeVisible();
  await page.getByRole("button", { name: "Clear local habits", exact: true }).click();
  await expect(page.getByRole("button", { name: "Confirm deletion", exact: true })).toBeDisabled();
  await page.getByRole("textbox", { name: "Type DELETE to confirm" }).fill("DELETE");
  await page.getByRole("button", { name: "Confirm deletion", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "Local guest habits cleared." })).toBeVisible();
  await page.reload();
  await expect(page.locator(".habit-card")).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});

test("Spanish backup preview explains new habits before restoration", async ({ page }) => {
  await page.goto("/");
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await page.getByRole("combobox", { name: "Language", exact: true }).selectOption("es");
  const model = { id: crypto.randomUUID(), name: "Hábito de prueba", description: "", category: "Focus", color: "sage", period: "Anytime", target: 1, unit: "vez", days: [0, 1, 2, 3, 4, 5, 6], created_on: "2026-01-01", updated_at: "2026-01-01T00:00:00.000Z", archived: false, entries: {} };
  await page.getByLabel("Elegir copia JSON").setInputFiles({ name: "backup.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify({ app: "Simply Habits", version: 1, habits: [model] })) });
  await expect(page.getByText("1 nuevos · 0 fusionados · 0 sin cambios · 0 bloqueados por eliminación", { exact: true })).toBeVisible();
  await expect(page.getByText("Hábito de prueba: Nuevo hábito", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Restaurar copia", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "Copia fusionada." })).toBeVisible();
  await page.getByRole("button", { name: "Mis hábitos", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Hábito de prueba", exact: true })).toBeVisible();
});

test("blocked preference storage reports failures without breaking language or theme", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.addInitScript(() => {
    Storage.prototype.getItem = () => { throw new DOMException("Storage denied", "SecurityError"); };
    Storage.prototype.setItem = () => { throw new DOMException("Storage denied", "SecurityError"); };
  });
  await page.goto("/");
  await expect(page.getByRole("alert").filter({ hasText: "Browser preference storage is unavailable." })).toBeVisible();
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await page.getByRole("combobox", { name: "Appearance", exact: true }).selectOption("dark");
  await expect(page.locator("html")).toHaveAttribute("data-theme", "dark");
  await page.getByRole("combobox", { name: "Language", exact: true }).selectOption("es");
  await expect(page.getByRole("combobox", { name: "Apariencia", exact: true })).toHaveValue("dark");
  await expect(page.getByRole("alert").filter({ hasText: "El almacenamiento de preferencias no está disponible." })).toBeVisible();
  await page.getByRole("combobox", { name: "Apariencia", exact: true }).selectOption("light");
  await expect(page.locator("html")).toHaveAttribute("data-theme", "light");
  expect(errors).toEqual([]);
});
